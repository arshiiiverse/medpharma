-- ---------- Admins ----------
create table if not exists public.admins (
  email text primary key
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- ---------- Store settings (single row) ----------
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  free_shipping int not null default 499 check (free_shipping >= 0),
  shipping_fee int not null default 49 check (shipping_fee >= 0),
  announcement text not null default 'Free delivery on orders above ₹499 · Delivered within 24 hours'
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- ---------- Products ----------
create table if not exists public.products (
  id int generated by default as identity primary key,
  name text not null,
  brand text not null,
  pack text not null,
  cat text not null,
  price int not null check (price > 0),
  mrp int not null check (mrp >= price),
  stock int not null default 0 check (stock >= 0),
  rating numeric(2,1) not null default 4.5,
  reviews int not null default 0,
  sold int not null default 0,
  is_new boolean not null default false,
  rx boolean not null default false,
  active boolean not null default true,
  img text not null,
  description text not null default '',
  highlights jsonb not null default '[]'::jsonb,
  usage text not null default '',
  created_at timestamptz not null default now()
);

-- ---------- Orders ----------
create table if not exists public.orders (
  id text primary key,
  created_at timestamptz not null default now(),
  status text not null default 'placed' check (status in ('placed', 'packed', 'out', 'delivered', 'cancelled')),
  items jsonb not null,
  subtotal int not null,
  shipping int not null,
  total int not null,
  name text not null,
  phone text not null,
  address text not null,
  city text not null,
  pin text not null,
  pay text not null
);
create index if not exists orders_created_idx on public.orders (created_at desc);

-- ---------- Lab & doctor bookings ----------
create table if not exists public.bookings (
  id text primary key,
  created_at timestamptz not null default now(),
  type text not null check (type in ('lab', 'consult')),
  title text not null,
  price int not null,
  when_text text not null,
  name text,
  phone text not null,
  status text not null default 'confirmed' check (status in ('confirmed', 'completed', 'cancelled'))
);

-- ---------- Contact messages ----------
create table if not exists public.messages (
  ticket text primary key,
  created_at timestamptz not null default now(),
  topic text not null,
  name text not null,
  email text not null,
  phone text,
  order_ref text,
  message text not null,
  status text not null default 'open' check (status in ('open', 'resolved'))
);

-- =========================================================
-- Row-level security: shoppers can only read the catalogue and settings.
-- Everything they create goes through the checked functions below.
-- Admins (emails in public.admins) can read and change everything.
-- =========================================================
alter table public.admins   enable row level security;
alter table public.settings enable row level security;
alter table public.products enable row level security;
alter table public.orders   enable row level security;
alter table public.bookings enable row level security;
alter table public.messages enable row level security;

drop policy if exists "admins read own row" on public.admins;
create policy "admins read own row" on public.admins for select using (public.is_admin());

drop policy if exists "settings readable" on public.settings;
create policy "settings readable" on public.settings for select using (true);
drop policy if exists "settings admin update" on public.settings;
create policy "settings admin update" on public.settings for update using (public.is_admin()) with check (public.is_admin());

drop policy if exists "products readable" on public.products;
create policy "products readable" on public.products for select using (active or public.is_admin());
drop policy if exists "products admin write" on public.products;
create policy "products admin write" on public.products for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "orders admin" on public.orders;
create policy "orders admin" on public.orders for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "bookings admin" on public.bookings;
create policy "bookings admin" on public.bookings for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "messages admin" on public.messages;
create policy "messages admin" on public.messages for all using (public.is_admin()) with check (public.is_admin());

-- =========================================================
-- Functions the store calls (they validate everything server-side)
-- =========================================================
create or replace function public.new_ref(prefix text) returns text
language sql volatile as $$
  select prefix || '-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
$$;

-- Place an order: prices come from the database (not the browser), stock is checked and reduced.
create or replace function public.place_order(
  p_items jsonb, p_name text, p_phone text, p_address text, p_city text, p_pin text, p_pay text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  it jsonb;
  prod public.products%rowtype;
  qty int;
  lines jsonb := '[]'::jsonb;
  sub int := 0;
  ship int;
  s public.settings%rowtype;
  oid text;
begin
  if p_name is null or length(trim(p_name)) < 2 then raise exception 'Please enter your name.'; end if;
  if coalesce(p_phone, '') !~ '^[6-9][0-9]{9}$' then raise exception 'Enter a valid 10-digit mobile number.'; end if;
  if length(trim(coalesce(p_address, ''))) < 8 then raise exception 'Please enter your delivery address.'; end if;
  if coalesce(p_pin, '') !~ '^(160|140|134)[0-9]{3}$' then raise exception 'We deliver only to PIN codes starting 160, 140 or 134.'; end if;
  if p_city not in ('Chandigarh', 'Mohali', 'Panchkula') then raise exception 'We only deliver in Chandigarh, Mohali and Panchkula.'; end if;
  if p_pay not in ('Cash on delivery', 'UPI on delivery') then raise exception 'Please choose a payment method.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'Your cart is empty.';
  end if;

  for it in select value from jsonb_array_elements(p_items) loop
    qty := (it ->> 'q')::int;
    if qty is null or qty < 1 or qty > 10 then raise exception 'Invalid quantity in cart.'; end if;
    select * into prod from public.products where id = (it ->> 'id')::int for update;
    if not found or not prod.active then raise exception 'A product in your cart is no longer available.'; end if;
    if prod.stock < qty then raise exception '% — only % left in stock.', prod.name, prod.stock; end if;
    update public.products set stock = stock - qty, sold = sold + qty where id = prod.id;
    sub := sub + prod.price * qty;
    lines := lines || jsonb_build_object('id', prod.id, 'q', qty, 'price', prod.price, 'name', prod.name, 'img', prod.img);
  end loop;

  select * into s from public.settings where id = 1;
  ship := case when sub >= s.free_shipping then 0 else s.shipping_fee end;
  oid := public.new_ref('MP');

  insert into public.orders (id, items, subtotal, shipping, total, name, phone, address, city, pin, pay)
  values (oid, lines, sub, ship, sub + ship, trim(p_name), p_phone, trim(p_address), p_city, p_pin, p_pay);

  return jsonb_build_object('id', oid, 'subtotal', sub, 'shipping', ship, 'total', sub + ship, 'items', lines);
end $$;

-- A shopper's own orders: they must know both the order ID and the phone number used.
create or replace function public.my_orders(p_refs jsonb) returns setof public.orders
language sql stable security definer set search_path = public as $$
  select o.* from public.orders o
  join jsonb_to_recordset(coalesce(p_refs, '[]'::jsonb)) as r(id text, phone text)
    on o.id = upper(r.id) and o.phone = r.phone
  order by o.created_at desc
  limit 50;
$$;

-- Shopper cancels their own order (only before it is out for delivery); stock goes back.
create or replace function public.cancel_order(p_id text, p_phone text) returns text
language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype; it jsonb;
begin
  select * into o from public.orders where id = upper(p_id) and phone = p_phone for update;
  if not found then raise exception 'Order not found.'; end if;
  if o.status not in ('placed', 'packed') then raise exception 'This order can no longer be cancelled.'; end if;
  update public.orders set status = 'cancelled' where id = o.id;
  for it in select value from jsonb_array_elements(o.items) loop
    update public.products set stock = stock + (it ->> 'q')::int, sold = greatest(0, sold - (it ->> 'q')::int) where id = (it ->> 'id')::int;
  end loop;
  return 'cancelled';
end $$;

-- Lab test / doctor booking
create or replace function public.add_booking(
  p_type text, p_title text, p_price int, p_when text, p_name text, p_phone text
) returns text
language plpgsql security definer set search_path = public as $$
declare ref text;
begin
  if p_type not in ('lab', 'consult') then raise exception 'Unknown booking type.'; end if;
  if coalesce(p_phone, '') !~ '^[6-9][0-9]{9}$' then raise exception 'Enter a valid 10-digit mobile number.'; end if;
  if length(coalesce(p_title, '')) not between 3 and 200 or length(coalesce(p_when, '')) not between 3 and 100 then raise exception 'Booking details are incomplete.'; end if;
  if p_price is null or p_price < 0 or p_price > 100000 then raise exception 'Invalid price.'; end if;
  ref := public.new_ref(case when p_type = 'lab' then 'LAB' else 'DOC' end);
  insert into public.bookings (id, type, title, price, when_text, name, phone)
  values (ref, p_type, trim(p_title), p_price, trim(p_when), nullif(trim(coalesce(p_name, '')), ''), p_phone);
  return ref;
end $$;

-- Contact form message
create or replace function public.add_message(
  p_topic text, p_name text, p_email text, p_phone text, p_order text, p_message text
) returns text
language plpgsql security definer set search_path = public as $$
declare ref text;
begin
  if length(trim(coalesce(p_name, ''))) < 2 then raise exception 'Please enter your name.'; end if;
  if coalesce(p_email, '') !~* '^[^@\s]+@[^@\s]+\.[^@\s]{2,}$' then raise exception 'Please enter a valid email address.'; end if;
  if length(trim(coalesce(p_message, ''))) not between 15 and 4000 then raise exception 'Please write a message of 15 to 4000 characters.'; end if;
  ref := public.new_ref('TKT');
  insert into public.messages (ticket, topic, name, email, phone, order_ref, message)
  values (ref, left(coalesce(p_topic, 'Something else'), 60), trim(p_name), trim(p_email),
          nullif(trim(coalesce(p_phone, '')), ''), nullif(upper(trim(coalesce(p_order, ''))), ''), trim(p_message));
  return ref;
end $$;

